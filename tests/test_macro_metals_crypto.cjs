'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const ids=['COMEX_GOLD','CME_CF_BRR','COMEX_COPPER','DCOILWTICO'];
const cards=[...html.matchAll(/<article class="rate-card" data-series="([^"]+)"[^>]*>([\s\S]*?)<\/article>/g)];
const idx=cards.findIndex(c=>c[1]===ids[0]);
assert.deepEqual(cards.slice(idx,idx+4).map(c=>c[1]),ids);
assert.match(cards[idx][2],/COMEX 금 선물.*gold\.settlements\.html/);
assert.match(cards[idx+1][2],/CME CF BRR.*cfbenchmarks\.com\/data\/indices\/BRR.*개별 거래소 종가는 아닙니다/);
assert.match(cards[idx+2][2],/COMEX 구리 선물.*copper\.settlements\.html/);
assert.match(cards[idx+3][2],/EIA Cushing WTI.*NYMEX 선물 결제가격과 다릅니다/);
for(const c of cards.slice(idx,idx+4))assert.doesNotMatch(c[2],/TradingView|Investing\.com|data-macro-chart/);
console.log('PASS Gold → Bitcoin → Copper → WTI, verified official-source links and distinct settlement/reference/spot bases.');
